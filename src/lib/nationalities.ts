export type Nationality = { code: string; ar: string; en: string };

export const NATIONALITIES: Nationality[] = LIST.map(([code, ar, en]) => ({ code, ar, en }));

const BY_CODE = new Map(NATIONALITIES.map((item) => [item.code, item]));
const BY_NAME = new Map(NATIONALITIES.flatMap((item) => [[item.ar, item] as const, [item.en.toLowerCase(), item] as const]));

/** The catalog entry for a stored code, or for an older row that stored the Arabic/English name. */
export function findNationality(value: string | null | undefined) {
  if (!value) return null;
  const trimmed = value.trim();
  return BY_CODE.get(trimmed.toUpperCase()) || BY_NAME.get(trimmed) || BY_NAME.get(trimmed.toLowerCase()) || null;
}

export function nationalityName(value: string | null | undefined, lang: Lang) {
  if (!value) return null;
  const item = findNationality(value);
  return item ? item[lang] : value;
}

export function nationalityBoth(value: string | null | undefined) {
  if (!value) return null;
  const item = findNationality(value);
  return item ? `${item.ar} / ${item.en}` : value;
}

/** Omani first, the rest alphabetical in the reader's language. */
export function nationalityOptions(lang: Lang) {
  const collator = new Intl.Collator(lang);
  return [...NATIONALITIES]
    .sort((a, b) => (a.code === DEFAULT_NATIONALITY ? -1 : b.code === DEFAULT_NATIONALITY ? 1 : collator.compare(a[lang], b[lang])))
    .map((item) => ({ value: item.code, label: item[lang], hint: lang === "en" ? item.ar : item.en }));
}
